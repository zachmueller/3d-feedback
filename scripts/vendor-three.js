#!/usr/bin/env node
/**
 * Copy the three.js files the viewer needs out of node_modules and into
 * viewer-app/vendor/, flattening their relative imports.
 *
 * The viewer is deliberately build-free: index.html declares an import map that
 * points the bare "three" specifier at vendor/three.module.js, and the examples
 * modules (GLTFLoader, TrackballControls, RoomEnvironment) are served as-is. Those
 * modules import each other by relative path, though, so this script walks the
 * import graph from the entry points, copies every file it reaches, and rewrites
 * each relative specifier to a flat "./<basename>" in the vendor directory.
 *
 * Self-hosting rather than loading from a CDN keeps a shared model URL working
 * with no third-party dependency at view time, and pins the version to whatever
 * package.json resolved.
 *
 * Runs on postinstall; also available as `npm run vendor`.
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const threeDir = path.join(root, 'node_modules', 'three');
const outDir = path.join(root, 'viewer-app', 'vendor');

/** Entry points, resolved relative to the three package root. */
const ENTRIES = [
  'build/three.module.js',
  'examples/jsm/loaders/GLTFLoader.js',
  'examples/jsm/controls/TrackballControls.js',
  'examples/jsm/environments/RoomEnvironment.js',
];

const THREE_MODULE_BASENAME = 'three.module.js';

if (!fs.existsSync(threeDir)) {
  console.error(
    '[vendor-three] node_modules/three is missing — run `npm install` first.',
  );
  process.exit(0); // don't fail an install that hasn't linked deps yet
}

fs.mkdirSync(outDir, { recursive: true });

const SPECIFIER = /(\bfrom\s*|\bimport\s*)(['"])([^'"]+)\2/g;

/**
 * A module specifier only ever appears on a line whose first token is `import`,
 * `export`, or the `}` closing a multi-line binding list. Restricting the
 * rewrite to those lines keeps it away from prose: three's own doc comments
 * contain strings like `from 'https://…/model.bin'`.
 */
const IMPORT_LINE = /^\s*(?:import\b|export\b|\})/;

/** Rewrite one module's specifiers, returning the files it pulls in. */
function rewrite(source, fileDir) {
  const pulled = [];
  const lines = source.split('\n').map((line) => {
    if (!IMPORT_LINE.test(line)) return line;
    return line.replace(SPECIFIER, (match, lead, quote, spec) => {
      if (spec === 'three') {
        return `${lead}${quote}./${THREE_MODULE_BASENAME}${quote}`;
      }
      if (spec.startsWith('./') || spec.startsWith('../')) {
        const resolved = path.resolve(fileDir, spec);
        pulled.push(resolved);
        return `${lead}${quote}./${path.basename(resolved)}${quote}`;
      }
      // Anything else would need its own import-map entry. Leave it alone and
      // say so, rather than silently rewriting something unresolvable.
      console.warn(`[vendor-three] leaving bare import "${spec}" untouched`);
      return match;
    });
  });
  return { code: lines.join('\n'), pulled };
}

const seen = new Set();
const queue = ENTRIES.map((rel) => path.join(threeDir, rel));
const copied = [];

while (queue.length) {
  const absolute = queue.shift();
  if (seen.has(absolute)) continue;
  seen.add(absolute);

  if (!fs.existsSync(absolute)) {
    console.error(`[vendor-three] expected file is missing: ${absolute}`);
    process.exit(1);
  }

  const source = fs.readFileSync(absolute, 'utf-8');
  const { code, pulled } = rewrite(source, path.dirname(absolute));
  fs.writeFileSync(path.join(outDir, path.basename(absolute)), code);
  copied.push(path.basename(absolute));
  queue.push(...pulled);

  // A dynamic import() would escape the static rewrite above and 404 at
  // runtime, so fail loudly if one shows up in a file we vendor.
  if (/\bimport\s*\(/.test(code)) {
    console.error(
      `[vendor-three] ${path.basename(absolute)} uses a dynamic import(); ` +
        'the flattening rewrite does not cover those.',
    );
    process.exit(1);
  }
}

const version = JSON.parse(
  fs.readFileSync(path.join(threeDir, 'package.json'), 'utf-8'),
).version;
fs.writeFileSync(
  path.join(outDir, 'VERSION'),
  `three@${version}\nGenerated by scripts/vendor-three.js — do not edit by hand.\n`,
);

console.log(
  `[vendor-three] vendored ${copied.length} files from three@${version}: ${copied.join(', ')}`,
);
